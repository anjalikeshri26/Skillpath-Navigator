import { api } from '../core/api.js';
import { bar, esc, formatClock, formatDate, percent, toast, $, $$ } from '../core/dom.js';
import { mount } from '../core/shell.js';
import { getMeta } from '../core/state.js';

let run = null;

export async function loadTests(params = {}) {
  stopTimer();
  const [meta, mastery, history] = await Promise.all([getMeta(), api('/quiz/mastery'), api('/quiz/history')]);
  const groups = {};
  meta.topics.forEach((t) => (groups[t.category] ??= []).push(t.name));
  const topicOptions = `<option>Mixed</option>` + Object.entries(groups).map(([category, names]) =>
    `<optgroup label="${esc(category)}">${names.map((n) => `<option ${n === params.topic ? 'selected' : ''}>${esc(n)}</option>`).join('')}</optgroup>`).join('');

  const page = mount('tests', `
    <div class="page-intro"><div><h2>Mock tests</h2>
      <p class="muted">Adaptive mode picks the level for each topic from your mastery. Questions you have completed are not repeated.</p></div></div>
    <section class="test-setup panel"><div class="field-grid">
      <label>Topic<select id="topic">${topicOptions}</select></label>
      <label>Difficulty<select id="difficulty"><option value="Adaptive">Adaptive (recommended)</option>${meta.difficulties.map((d) => `<option>${esc(d)}</option>`).join('')}</select></label>
      <label>Questions<select id="limit"><option>5</option><option selected>8</option><option>10</option><option>15</option></select></label></div>
      <button class="btn btn-dark" id="start">Start test</button>
      <p class="sp-field-note">${meta.ai.configured ? 'When the bank runs low, new questions are generated by Groq and independently verified before use.' : 'Groq is not configured, so only the built-in question bank is used.'}</p></section>
    <div id="testArea"></div>
    <div class="sp-grid-2">
      <section class="panel"><div class="panel-heading"><h3>Mastery by topic</h3></div>${mastery.map((m) => `<div class="sp-bar-row"><div class="label">${esc(m.topic)}<small>${m.reliable ? '' : 'early estimate, '}next: ${esc(m.recommended_difficulty)}</small></div>${bar(m.mastery, { early: !m.reliable })}<b>${percent(m.mastery)}%</b></div>`).join('') || '<p class="sp-empty">Take a test to see mastery here.</p>'}</section>
      <section class="panel history-panel"><div class="panel-heading"><h3>Recent attempts</h3></div>${history.slice(0, 8).map((h) => `<div class="history-row"><span><b>${esc(h.topic)}</b><small>${formatDate(h.date)} · ${esc(h.difficulty)} · ${h.correct}/${h.total}</small></span><strong>${h.score}%</strong></div>`).join('') || '<p class="sp-empty">No attempts yet.</p>'}</section>
    </div>`);

  $('#start', page).addEventListener('click', async (event) => {
    event.target.disabled = true;
    try {
      const data = await api('/quiz/sessions', { method: 'POST', json: { topic: $('#topic', page).value, difficulty: $('#difficulty', page).value, limit: Number($('#limit', page).value) } });
      run = { id: data.session_id, questions: data.questions, answers: {}, index: 0, deadline: Date.now() + data.seconds_allowed * 1000, notices: data.notices, submitting: false };
      renderRunner();
    } catch (error) { toast(error.message); }
    finally { event.target.disabled = false; }
  });
}

function stopTimer() {
  if (run?.timer) clearInterval(run.timer);
}

function renderRunner() {
  const area = $('#testArea');
  area.innerHTML = `<section class="panel active-test"><div class="test-live-head"><div><h3>Test in progress</h3></div><div class="timer" id="timer"></div></div>
    ${run.notices.map((n) => `<div class="sp-notice">${esc(n)}</div>`).join('')}
    <div class="test-progress"><i></i></div><div id="questionMount"></div>
    <div class="test-controls"><button class="btn btn-outline" id="prev">Previous</button><span id="count"></span><button class="btn btn-dark" id="next">Next</button><button class="btn btn-dark" id="submit" hidden>Submit test</button></div></section>`;
  $('#prev').onclick = () => { run.index--; paint(); };
  $('#next').onclick = () => { run.index++; paint(); };
  $('#submit').onclick = () => {
    const unanswered = run.questions.length - Object.keys(run.answers).length;
    if (!unanswered || confirm(`${unanswered} question(s) are unanswered and will be marked incorrect. Submit anyway?`)) submit();
  };
  stopTimer();
  run.timer = setInterval(tick, 500);
  tick();
  paint();
  area.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function tick() {
  const el = $('#timer');
  if (!el) { stopTimer(); return; } // the learner left the page
  const left = Math.ceil((run.deadline - Date.now()) / 1000);
  el.textContent = formatClock(left);
  if (left <= 0) submit();
}

function paint() {
  const q = run.questions[run.index];
  const last = run.index === run.questions.length - 1;
  $('#questionMount').innerHTML = `<div class="question-card"><div class="section-kicker">${esc(q.topic)} · ${esc(q.difficulty)} · question ${run.index + 1} of ${run.questions.length}</div><h3>${esc(q.prompt)}</h3>
    <div class="option-list">${q.options.map((text, i) => `<button class="option ${run.answers[q.id] === i ? 'chosen' : ''}" data-option="${i}"><span>${String.fromCharCode(65 + i)}</span>${esc(text)}</button>`).join('')}</div></div>`;
  $$('[data-option]').forEach((b) => b.addEventListener('click', () => { run.answers[q.id] = Number(b.dataset.option); paint(); }));
  $('#count').textContent = `${Object.keys(run.answers).length} answered`;
  $('.test-progress i').style.width = `${((run.index + 1) / run.questions.length) * 100}%`;
  $('#prev').disabled = run.index === 0;
  $('#next').hidden = last;
  $('#submit').hidden = !last;
}

async function submit() {
  if (run.submitting) return;
  run.submitting = true;
  stopTimer();
  try {
    const answers = run.questions.map((q) => ({ question_id: q.id, selected: run.answers[q.id] ?? null }));
    const result = await api(`/quiz/sessions/${run.id}/submit`, { method: 'POST', json: { answers } });
    renderResult(result);
  } catch (error) {
    run.submitting = false;
    toast(error.message);
  }
}

function renderResult(r) {
  const changes = r.mastery_changes.map((c) => {
    const delta = Math.round((c.after - c.before) * 100);
    return `<div class="sp-bar-row"><div class="label">${esc(c.topic)}<small>next: ${esc(r.next_difficulty[c.topic])}</small></div>${bar(c.after)}<b>${delta >= 0 ? '+' : ''}${delta}</b></div>`;
  }).join('');
  $('#testArea').innerHTML = `<section class="panel result-panel sp-stack">
    <div><div class="result-score">${r.score}<small>%</small></div><h3>${r.correct} of ${r.total} correct${r.skipped ? `, ${r.skipped} skipped` : ''}</h3></div>
    <div><h4>Topic breakdown</h4>${r.per_topic.map((t) => `<p>${esc(t.topic)}: ${t.correct}/${t.total}</p>`).join('')}</div>
    <div><h4>Mastery change</h4>${changes}<p class="sp-field-note">Points of mastery gained or lost. Harder questions move the estimate more.</p></div>
    <div><h4>Review</h4>${r.details.map(reviewItem).join('')}</div>
    <div><a class="btn btn-dark" href="#/tests" id="again">Take another test</a></div></section>`;
  $('#again').addEventListener('click', (e) => { e.preventDefault(); run = null; loadTests(); });
  $$('[data-report]').forEach((b) => b.addEventListener('click', async () => {
    try {
      await api(`/quiz/questions/${b.dataset.id}/report`, { method: 'POST', json: { reason: b.dataset.report } });
      b.parentElement.textContent = 'Thanks, this question was flagged for review.';
    } catch (error) { toast(error.message); }
  }));
  $('#testArea').scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function reviewItem(d, i) {
  const verdict = d.skipped ? 'Skipped' : d.is_correct ? 'Correct' : 'Incorrect';
  const options = d.options.map((text, pos) => {
    const cls = pos === d.correct_position ? 'is-correct' : pos === d.selected_position ? 'is-wrong' : '';
    return `<div class="option ${cls}"><span>${String.fromCharCode(65 + pos)}</span>${esc(text)}</div>`;
  }).join('');
  return `<div class="sp-review"><h4>${i + 1}. ${esc(d.prompt)} <small class="muted">(${esc(d.topic)}, ${esc(d.difficulty)}) ${verdict}</small></h4><div class="option-list">${options}</div>
    <p class="muted">${esc(d.explanation)}</p>
    <p class="sp-field-note">Think this question is wrong? <button class="sp-link-button" data-report="wrong_answer" data-id="${d.question_id}">The answer is wrong</button> · <button class="sp-link-button" data-report="unclear" data-id="${d.question_id}">It is unclear</button></p></div>`;
}
