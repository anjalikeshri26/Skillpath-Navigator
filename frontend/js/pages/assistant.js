import { api } from '../core/api.js';
import { esc, toast, $ } from '../core/dom.js';
import { mount } from '../core/shell.js';
import { session } from '../core/state.js';

const history = [];

export function loadAssistant() {
  const name = esc((session.user?.name || 'there').split(' ')[0]);
  const page = mount('assistant', `
    <div class="page-intro"><div><h2>Ask the tutor</h2>
      <p class="muted">Placement-focused help. It knows your target role and your weakest quiz topics, and answers are generated by Groq, so check anything important.</p></div></div>
    <section class="chat-panel panel"><div class="chat-head"><div class="assistant-avatar">✳</div><div><b>SkillPath tutor</b><small>${esc(session.user?.target_role || '')}</small></div></div>
      <div class="chat-messages" id="chatMessages" aria-live="polite"><div class="chat-bubble bot">Hi ${name}. What are you working through today?</div></div>
      <form class="chat-input" id="chatForm"><input id="chatText" maxlength="2000" placeholder="Ask a question or paste a concept" required autocomplete="off"><button class="btn btn-dark">Send</button></form></section>`);
  history.length = 0;
  $('#chatForm', page).addEventListener('submit', send);
}

function bubble(kind, text) {
  const box = $('#chatMessages');
  const el = document.createElement('div');
  el.className = `chat-bubble ${kind}`;
  el.textContent = text; // textContent keeps model output from injecting markup
  el.style.whiteSpace = 'pre-wrap';
  box.append(el);
  box.scrollTop = box.scrollHeight;
  return el;
}

async function send(event) {
  event.preventDefault();
  const input = $('#chatText');
  const message = input.value.trim();
  if (!message) return;
  input.value = '';
  bubble('user', message);
  const pending = bubble('bot', 'Thinking…');
  try {
    const { answer } = await api('/assistant', { method: 'POST', json: { message, history: history.slice(-8) } });
    pending.textContent = answer;
    history.push({ role: 'user', text: message }, { role: 'assistant', text: answer });
  } catch (error) {
    pending.textContent = error.message;
    pending.classList.add('error');
    toast(error.message);
  }
}
